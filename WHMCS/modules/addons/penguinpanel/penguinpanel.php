function penguinpanel_output($vars)
{
    $h = static function ($value) {
        return htmlspecialchars((string) $value, ENT_QUOTES, 'UTF-8');
    };

    $moduleLink = isset($vars['modulelink']) ? (string) $vars['modulelink'] : 'addonmodules.php?module=penguinpanel';
    $panelUrl = rtrim(trim((string) ($vars['panel_url'] ?? '')), '/');
    $apiKey = trim((string) ($vars['api_key'] ?? ''));
    $adminUrl = rtrim(trim((string) ($vars['panel_admin_url'] ?? $panelUrl)), '/');

    $serverModulePath = ROOTDIR . '/modules/servers/penguinpanel/penguinpanel.php';
    $serverModuleInstalled = is_file($serverModulePath);

    $serviceCounts = [];
    $servers = [];
    $dbError = '';

    try {
        $rows = Capsule::table('tblhosting')
            ->join('tblproducts', 'tblproducts.id', '=', 'tblhosting.packageid')
            ->where('tblproducts.servertype', 'penguinpanel')
            ->select('tblhosting.domainstatus', Capsule::raw('COUNT(*) as total'))
            ->groupBy('tblhosting.domainstatus')
            ->get();
        foreach ($rows as $row) {
            $serviceCounts[(string) $row->domainstatus] = (int) $row->total;
        }

        $servers = Capsule::table('tblservers')
            ->where('type', 'penguinpanel')
            ->select('id', 'name', 'hostname', 'ipaddress', 'port', 'secure', 'disabled')
            ->orderBy('id')
            ->get()
            ->all();
    } catch (\Throwable $e) {
        $dbError = $e->getMessage();
    }

    $health = null;
    $catalog = null;
    $apiError = '';

    if ($panelUrl !== '' && $apiKey !== '') {
        try {
            $client = new \PenguinPanel\WhmcsAddon\ApiClient($panelUrl, $apiKey);
            $health = $client->get('/api/whmcs/health', 20);
            $catalog = $client->get('/api/whmcs/catalog', 30);
        } catch (\Throwable $e) {
            $apiError = $e->getMessage();
        }
    }

    $templates = is_array($catalog['templates'] ?? null) ? $catalog['templates'] : [];
    $roots = is_array($catalog['storageRoots'] ?? null) ? $catalog['storageRoots'] : [];

    $statusClass = $health ? 'pp-good' : 'pp-bad';
    $statusText = $health ? 'Connected' : ($apiKey === '' ? 'Not configured' : 'Connection failed');

    echo '<style>
    .pp-wrap{max-width:1220px}.pp-hero{display:flex;align-items:center;justify-content:space-between;gap:20px;padding:22px 24px;background:#17202a;color:#fff;border-radius:10px;margin:0 0 18px}.pp-hero h2{margin:0 0 5px;color:#fff}.pp-hero p{margin:0;color:#cad3dc}.pp-badge{display:inline-block;padding:6px 11px;border-radius:999px;font-weight:700;font-size:12px}.pp-good{background:#d9f6e5;color:#176b3a}.pp-bad{background:#fde2e2;color:#9a2424}.pp-grid{display:grid;grid-template-columns:repeat(auto-fit,minmax(220px,1fr));gap:14px;margin-bottom:18px}.pp-card{background:#fff;border:1px solid #dfe4ea;border-radius:9px;padding:17px;box-shadow:0 1px 2px rgba(0,0,0,.04)}.pp-card h3{margin:0 0 8px;font-size:14px;color:#65717d;text-transform:uppercase;letter-spacing:.03em}.pp-big{font-size:26px;font-weight:700;color:#202b36}.pp-muted{color:#7b8794}.pp-section{background:#fff;border:1px solid #dfe4ea;border-radius:9px;margin:0 0 18px;overflow:hidden}.pp-section-head{padding:14px 17px;border-bottom:1px solid #e6eaee;font-weight:700;font-size:16px}.pp-section-body{padding:17px}.pp-table{width:100%;border-collapse:collapse}.pp-table th,.pp-table td{padding:9px 10px;border-bottom:1px solid #edf0f2;text-align:left}.pp-table th{font-size:12px;text-transform:uppercase;color:#6f7b86}.pp-alert{padding:12px 14px;border-radius:7px;margin-bottom:14px;background:#fff3cd;border:1px solid #ffe69c;color:#664d03}.pp-error{background:#f8d7da;border-color:#f5c2c7;color:#842029}.pp-actions a{margin-right:8px}.pp-code{font-family:monospace;background:#f4f6f8;padding:2px 5px;border-radius:4px}
    </style>';

    echo '<div class="pp-wrap">';
    echo '<div class="pp-hero"><div><h2>🐧 PenguinPanel Integration</h2><p>WHMCS ↔ PenguinPanel ↔ Hyper-V</p></div><span class="pp-badge ' . $statusClass . '">' . $h($statusText) . '</span></div>';

    if (!$serverModuleInstalled) {
        echo '<div class="pp-alert pp-error"><strong>Server module missing.</strong> Expected <span class="pp-code">/modules/servers/penguinpanel/penguinpanel.php</span>.</div>';
    }
    if ($apiKey === '') {
        echo '<div class="pp-alert"><strong>Finish configuration:</strong> click Configure on the Addon Modules page and save your PenguinPanel API key.</div>';
    }
    if ($apiError !== '') {
        echo '<div class="pp-alert pp-error"><strong>API check failed:</strong> ' . $h($apiError) . '</div>';
    }
    if ($dbError !== '') {
        echo '<div class="pp-alert pp-error"><strong>WHMCS inventory check failed:</strong> ' . $h($dbError) . '</div>';
    }

    $active = $serviceCounts['Active'] ?? 0;
    $suspended = $serviceCounts['Suspended'] ?? 0;
    $pending = $serviceCounts['Pending'] ?? 0;
    $terminated = $serviceCounts['Terminated'] ?? 0;
    $total = array_sum($serviceCounts);

    echo '<div class="pp-grid">';
    pp_card('API', $statusText, $panelUrl !== '' ? $panelUrl : 'Configure addon');
    pp_card('WHMCS Services', $total, 'Active ' . $active . ' · Suspended ' . $suspended . ' · Pending ' . $pending);
    pp_card('OS Templates', count($templates), $health ? 'Live from PenguinPanel' : 'API not available');
    pp_card('Storage Roots', count($roots), $health ? 'Live from PenguinPanel' : 'API not available');
    echo '</div>';

    echo '<div class="pp-section"><div class="pp-section-head">Integration status</div><div class="pp-section-body">';
    echo '<table class="pp-table"><tbody>';
    pp_row('Addon module', 'Installed / active');
    pp_row('Provisioning module', $serverModuleInstalled ? 'Installed' : 'Missing');
    pp_row('PenguinPanel API', $statusText);
    pp_row('API version', $health['version'] ?? '—');
    pp_row('Server entries', count($servers));
    pp_row('Terminated WHMCS services', $terminated);
    echo '</tbody></table>';
    echo '<div class="pp-actions" style="margin-top:15px"><a class="btn btn-primary" href="' . $h($moduleLink) . '">Refresh checks</a>';
    if ($adminUrl !== '') {
        echo '<a class="btn btn-default" target="_blank" rel="noopener" href="' . $h($adminUrl) . '">Open PenguinPanel</a>';
    }
    echo '</div></div></div>';

    echo '<div class="pp-section"><div class="pp-section-head">WHMCS PenguinPanel servers</div><div class="pp-section-body">';
    if (!$servers) {
        echo '<p class="pp-muted">No WHMCS server entry using module <span class="pp-code">penguinpanel</span> was found yet. Add one under System Settings → Servers.</p>';
    } else {
        echo '<table class="pp-table"><thead><tr><th>Name</th><th>Host</th><th>Port</th><th>SSL</th><th>Enabled</th></tr></thead><tbody>';
        foreach ($servers as $server) {
            echo '<tr><td>' . $h($server->name ?: ('Server #' . $server->id)) . '</td><td>' . $h($server->hostname ?: $server->ipaddress) . '</td><td>' . $h($server->port ?: '443') . '</td><td>' . ((int) $server->secure ? 'Yes' : 'No') . '</td><td>' . ((int) $server->disabled ? 'No' : 'Yes') . '</td></tr>';
        }
        echo '</tbody></table>';
    }
    echo '</div></div>';

    echo '<div class="pp-section"><div class="pp-section-head">Live PenguinPanel catalog</div><div class="pp-section-body">';
    if (!$catalog) {
        echo '<p class="pp-muted">Catalog information will appear here after the API connection succeeds.</p>';
    } else {
        echo '<table class="pp-table"><tbody>';
        pp_row('Default storage root', $catalog['defaultStorageRoot'] ?? '—');
        pp_row('Default generation', $catalog['defaultGeneration'] ?? '—');
        pp_row('Secure Boot default', !empty($catalog['defaultSecureBoot']) ? 'Enabled' : 'Disabled');
        pp_row('RDP allocation range', (string)($catalog['rdpPortStart'] ?? '—') . ' - ' . (string)($catalog['rdpPortEnd'] ?? '—'));
        pp_row('FiveM allocation range', (string)($catalog['fiveMPortStart'] ?? '—') . ' - ' . (string)($catalog['fiveMPortEnd'] ?? '—'));
        echo '</tbody></table>';

        if ($templates) {
            echo '<h4 style="margin-top:18px">Templates</h4><table class="pp-table"><thead><tr><th>ID</th><th>Name</th><th>Operating system</th></tr></thead><tbody>';
            foreach ($templates as $template) {
                echo '<tr><td>' . $h($template['id'] ?? '') . '</td><td>' . $h($template['name'] ?? '') . '</td><td>' . $h($template['operatingSystem'] ?? '') . '</td></tr>';
            }
            echo '</tbody></table>';
        }
        if ($roots) {
            echo '<h4 style="margin-top:18px">Storage roots</h4><ul>';
            foreach ($roots as $root) {
                echo '<li><span class="pp-code">' . $h($root) . '</span></li>';
            }
            echo '</ul>';
        }
    }
    echo '</div></div>';
    echo '</div>';
}

function pp_card($title, $value, $detail)
{
    echo '<div class="pp-card"><h3>' . pp_h($title) . '</h3><div class="pp-big">' . pp_h($value) . '</div><div class="pp-muted">' . pp_h($detail) . '</div></div>';
}

function pp_row($label, $value)
{
    echo '<tr><th style="width:220px">' . pp_h($label) . '</th><td>' . pp_h($value) . '</td></tr>';
}

function pp_h($value)
{
    return htmlspecialchars((string) $value, ENT_QUOTES, 'UTF-8');
}
